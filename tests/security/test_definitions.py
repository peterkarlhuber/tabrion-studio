def _admin(url: str) -> sqlalchemy.Engine:
    return sqlalchemy.create_engine(sqlalchemy.make_url(url).set(drivername="postgresql+psycopg"))


def _registry(url: str) -> ConnectionRegistry:
    parsed = sqlalchemy.make_url(url)
    profile = Profile(
        "pg",
        "postgresql",
        "dev",
        host=parsed.host,
        port=parsed.port,
        database=parsed.database,
        user=parsed.username,
        password=SecretRef("keyring", ""),
        sslmode="prefer",
    )
    return ConnectionRegistry(Source(profiles={"user:pg": profile}, passwords={"user:pg": parsed.password or ""}))


def _quote(engine: sqlalchemy.Engine, name: str) -> str:
    return engine.dialect.identifier_preparer.quote(name)


def create_schemas(url: str) -> str:
    """The three schemas of the comparison, created anew; returns the role's name as an identifier."""
    admin = _admin(url)
    try:
        with admin.begin() as connection:
            for schema in (PARTS, MEASUREMENTS, EXTRAS):
                connection.exec_driver_sql(f"DROP SCHEMA IF EXISTS {schema} CASCADE")
                connection.exec_driver_sql(f"CREATE SCHEMA {schema}")
            for schema, metadata in (
                (PARTS, reference_apps.parts("postgresql")),
                (MEASUREMENTS, reference_apps.measurements_upstream()),
            ):
                metadata.create_all(connection.execution_options(schema_translate_map={None: schema}))
            role = _quote(admin, str(connection.exec_driver_sql("SELECT current_user").scalar()))
            for statement in split_statements(EXTRAS_SQL.format(s=EXTRAS, role=role)):
                connection.exec_driver_sql(statement)
        return role
    finally:
        admin.dispose()


def drop_schemas(url: str) -> None:
    admin = _admin(url)
    try:
        with admin.begin() as connection:
            for schema in (PARTS, MEASUREMENTS, EXTRAS):
                connection.exec_driver_sql(f"DROP SCHEMA IF EXISTS {schema} CASCADE")
    finally:
        admin.dispose()


