"""STU-022: DDL, row-level security policies and row estimates, read-only, for the explorer's objects.

Acceptance (09 backlog STU-022): "DDL-Vergleich mit ``pg_dump --schema-only`` für Referenz-Apps". The reference
applications are TABRION's ``examples/parts`` and ``examples/measurements`` (copied schemas,
:mod:`tests.support.reference_apps`). On PostgreSQL each one is created in a schema of its own, and the statements of
Studio's DDL for every object of that schema must be exactly the statements of ``pg_dump --schema-only --no-owner
--no-privileges -n <schema>``:

* always against the recorded ``pg_dump`` output in ``ddl_fixtures/`` (pg_dump 16.15 against PostgreSQL 16.15), so
  the comparison runs on every server, also where no matching ``pg_dump`` is installed;
* and against a live ``pg_dump`` run when one is on ``PATH`` and can dump the server (pg_dump refuses a server of a
  newer major version: the CI job's runner has the client of its Ubuntu image, the server is PostgreSQL 17).

A third schema (``extras``) has what the reference applications lack: row-level security with policies, views, a
materialized view, a partitioned table, inheritance, sequences, triggers, comments, quoted names. On SQLite the DDL is
the stored text of ``sqlite_master``, compared with SQLite's own record and with the reference app's migrations.

Everything runs through ``OpenConnection.fetch``, so through the statement check (``check_statement``) and one
``Database.read()`` per statement; a spy shows that only ``SELECT`` statements were sent. The SQLite tests always run;
the PostgreSQL tests need ``TABRION_STUDIO_TEST_POSTGRES`` (``postgres_superuser``: also
``TABRION_STUDIO_TEST_POSTGRES_SUPERUSER``) and create and drop their own schemas.
"""

