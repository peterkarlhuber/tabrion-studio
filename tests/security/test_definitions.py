def recorded(path: Path, name: str) -> list[str]:
    """SQLite's own record of ``name``'s DDL (what ``.schema`` prints): ``sqlite_master`` read directly."""
    reader = sqlite3.connect(path)
    try:
        rows = reader.execute(
            "SELECT sql FROM sqlite_master WHERE tbl_name = ? AND sql IS NOT NULL ORDER BY name <> ?, type, name",
            (name, name),
        ).fetchall()
    finally:
        reader.close()
    return [row[0] for row in rows]


