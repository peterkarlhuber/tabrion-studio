def test_the_type_editors_values_are_written_and_read_back_as_old(pg: Env) -> None:
    """The values the page's editors send (an enum label, text with trailing spaces beyond the length, integer text,
    nested arrays with NULL elements, a timestamp without and a time with an offset, an enum array as array text) are
    written; an identity ALWAYS key and a generated column are left to the database; the viewer's values
    of the new row are then the old values of an update that runs without a false conflict."""
    _typed(pg)
    values = {
        "mood": "bad",
        "short": "abcde   ",
        "code": "ab",
        "small": "7",
        "nums": [[1, 2], [3, None]],
        "tags": [["ab", "c"], [None, "d"]],
        "stamp": "2024-01-01 10:00:00",
        "clock": "10:00:00+02:00",
        "label": "",
        "moods": "{ok,bad}",
        "days": ["2024-02-29", None],
        "amounts": [" 1.5 ", "-0.25"],
        "ids": ["A0EEBC99-9C0B-4EF8-BB6D-6BB9BD380A11"],
        "seen": [["2024-01-02 03:04:05+02:00"], ["2024-12-31 24:00Z"]],
    }
    done = _run_on(pg, "typed", TYPED_COLUMNS, [{"op": "insert", "values": values}])
    assert done.status_code == 200, done.text
    assert pg.sql(
        "SELECT mood::text, short, code, small, nums::text, tags::text, stamp::text, clock::text, twice, label,"
        " moods::text, days::text, amounts::text, ids::text, seen::text FROM {p}.typed"
    ) == [
        (
            "bad",
            "abcde",
            "ab",
            7,
            "{{1,2},{3,NULL}}",
            "{{ab,c},{NULL,d}}",
            "2024-01-01 10:00:00",
            "10:00:00+02",
            14,
            "",
            "{ok,bad}",
            "{2024-02-29,NULL}",
            "{1.50,-0.25}",
            "{a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11}",
            '{{"2024-01-02 01:04:05+00"},{"2025-01-01 00:00:00+00"}}',
        )
    ]
    query = urlencode({"schema": pg.prefix, "name": "typed", "limit": 10})
    page = pg.env.send("GET", f"/api/connections/{pg.connection_id}/rows?{query}").json()
    old = dict(zip([column["name"] for column in page["columns"]], page["rows"][0], strict=True))
    assert (old["days"], old["amounts"], old["ids"]) == (
        ["2024-02-29", None],
        ["1.50", "-0.25"],
        ["a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11"],
    )
    new = {"label": "x", "tags": [None, "e"], "days": ["2024-03-01"], "amounts": ["99.99"]}
    change = {"op": "update", "key": {"id": old["id"]}, "old": old, "new": new}
    updated = _run_on(pg, "typed", list(old), [change])
    assert updated.status_code == 200, updated.text
    assert pg.sql("SELECT label, tags::text, days::text, amounts::text FROM {p}.typed") == [
        ("x", "{NULL,e}", "{2024-03-01}", "{99.99}")
    ]


def test_a_time_of_24_00_is_written_and_compared_on_every_python_version(pg: Env) -> None:
    """G2-03 of the G-S2 gate review: the check takes 24:00 as PostgreSQL does, and the run binds it as text, so the
    database stores it as it is (``time`` keeps ``24:00:00``) whatever Python's ``fromisoformat`` takes; the viewer's
    24:00 is then an old value that matches without a false conflict."""
    _table(pg, "clock", "id integer PRIMARY KEY, t time, tz timetz, s timestamp, st timestamptz")
    columns = ["id", "t", "tz", "s", "st"]
    values = {"id": 1, "t": "24:00", "tz": "24:00:00+02:00", "s": "2024-12-31 24:00", "st": "2024-12-31T24:00:00.000Z"}
    done = _run_on(pg, "clock", columns, [{"op": "insert", "values": values}])
    assert done.status_code == 200, done.text
    assert pg.sql("SELECT t::text, tz::text, s::text, st = '2025-01-01 00:00:00+00'::timestamptz FROM {p}.clock") == [
        ("24:00:00", "24:00:00+02", "2025-01-01 00:00:00", True)
    ]
    old = {"id": 1, "t": "24:00:00", "tz": "24:00:00+02", "s": "2025-01-01 00:00:00", "st": "2025-01-01 00:00:00+00"}
    change = {"op": "update", "key": {"id": 1}, "old": old, "new": {"t": "24:00:00.000", "s": "2025-01-01 24:00"}}
    updated = _run_on(pg, "clock", columns, [change])
    assert updated.status_code == 200, updated.text
    assert pg.sql("SELECT t::text, s::text FROM {p}.clock") == [("24:00:00", "2025-01-02 00:00:00")]
