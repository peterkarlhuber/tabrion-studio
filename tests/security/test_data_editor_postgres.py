def test_a_rule_that_changes_no_row_rolls_the_changeset_back(pg: Env) -> None:
    """``DO INSTEAD NOTHING`` makes the insert change 0 rows: not 1, so everything is rolled back; the preview names
    the rule and the trigger (TX-16, review I-1 of tabrion #78)."""
    rows = pg.page()
    changes = [
        {"op": "update", "key": {"id": 102}, "old": _old(rows[102]), "new": {"note": "x"}},
        {"op": "insert", "values": {"material": "skip"}},
    ]
    preview = pg.plan(changes).json()
    target = preview["targets"][0]
    assert target["triggers"] == [{"name": "parts_touch", "timing": "before", "events": ["update"], "enabled": True}]
    assert target["rules"] == [{"name": "parts_skip", "event": "insert", "instead": True}]
    assert {"plan.triggers", "plan.rules"} <= set(preview["risks"])
    refused = pg.run(changes)
    assert (refused.status_code, refused.json()["code"]) == (400, "studio.data_editor_rowcount"), refused.text
    assert pg.sql("SELECT note FROM {p}.parts WHERE id = 102") == [(None,)]


