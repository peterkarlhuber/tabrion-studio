def _old(row: dict[str, Any]) -> dict[str, Any]:
    return dict(row)


def test_a_changeset_of_many_types_runs_with_the_viewers_values_as_old(pg: Env) -> None:
    """The viewer's values (decimal, date and time text, JSON, base64 bytes, a real read with
    ``extra_float_digits=3``, a UUID) are the ``old`` values; none reports a false conflict (N-5)."""
    rows = pg.page()
    steel, copper = rows[101], rows[102]
    assert steel["raw"] == {"base64": "AQI="}
    changes = [
        {
            "op": "update",
            "key": {"id": 101},
            "old": _old(steel),
            "new": {
                "material": "Iron",
                "price": "2.75",
                "made": "2025-05-06",
                "ok": False,
                "doc": {"b": [1, 2]},
                "raw": {"base64": "AwQ="},
                "weight": "0.5",
                "seen": "2025-01-01T10:00:00+02:00",
            },
        },
        {"op": "insert", "values": {"material": "Titan", "price": "3", "ok": "true", "tag": None}},
        {"op": "delete", "key": {"id": 102}, "old": _old(copper)},
    ]
    response = pg.run(changes)
    assert response.status_code == 200, response.text
    assert response.json()["rows"] == {"updated": 1, "inserted": 1, "deleted": 1}
    found = pg.sql(
        "SELECT id, material, price::text, made::text, ok, doc::text, encode(raw, 'hex'), weight,"
        " seen AT TIME ZONE 'UTC' FROM {p}.parts ORDER BY id"
    )
    assert [row[:8] for row in found] == [
        (1, "Titan", "3.00", None, True, None, None, None),
        (101, "Iron", "2.75", "2025-05-06", False, '{"b": [1, 2]}', "0304", 0.5),
    ]
    assert str(found[1][8]) == "2025-01-01 08:00:00"


def test_an_optimistic_conflict_rolls_back_under_the_hostile_search_path(pg: Env) -> None:
    """The write role's own search_path puts a schema with an always-true ``=`` for text first; the statements are
    schema-qualified and the session's search_path is pinned, so a concurrent change of a shown text value is still a
    conflict (K-2, TX-09). The insert before it is rolled back too."""
    rows = pg.page()
    changes = [
        {"op": "insert", "values": {"material": CANARY_VALUE}},
        {"op": "update", "key": {"id": 101}, "old": _old(rows[101]), "new": {"price": "9.99"}},
    ]
    preview = pg.plan(changes)
    assert preview.status_code == 201
    pg.sql("UPDATE {p}.parts SET note = 'changed' WHERE id = 101")
    doc = preview.json()
    confirm = {"connection_id": pg.connection_id, "plan_hash": doc["plan_hash"], "typed": doc["confirm_text"]}
    assert pg.env.send("POST", "/api/write/plans/confirm", confirm).status_code == 200
    refused = pg.env.send(
        "POST", "/api/write/plans/execute", {"connection_id": pg.connection_id, "plan_hash": doc["plan_hash"]}
    )
    assert (refused.status_code, refused.json()["code"]) == (400, "studio.data_editor_conflict"), refused.text
    assert CANARY_VALUE not in refused.text
    assert pg.sql("SELECT count(*), max(price)::text FROM {p}.parts") == [(2, "1.50")]


