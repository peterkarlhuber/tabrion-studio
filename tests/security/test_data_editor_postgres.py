"""STU-026 against PostgreSQL: the Data Editor's changesets on a table of many types, with the values as the viewer
shows them as ``old`` (every shown column, review L-1 of tabrion #78), under the write role with its hostile
``search_path`` and shadowing ``=`` operator (K-2, TX-16): the happy path, an optimistic conflict, a rule that makes
an insert change 0 rows (the whole changeset rolls back), a NULL old value, the preview naming the trigger and the
rule, and the refused targets (a view, a partitioned table, a table without a primary key).

The roles and the schema come from ``test_write_postgres.py``'s ``roles`` fixture (marker ``postgres_superuser``).
"""

from __future__ import annotations

from collections.abc import Iterator
from pathlib import Path
from typing import Any
from urllib.parse import urlencode

import pytest
import sqlalchemy

from tests.security.test_write_postgres import PG_SUPERUSER_URL, PG_URL, roles  # noqa: F401 - the fixture
from tests.support.write import CANARY_VALUE, DATA_EDITOR, WriteEnv

pytestmark = [pytest.mark.security, pytest.mark.postgres_superuser]

EXECUTOR = "data_editor.changeset"
COLUMNS = ["id", "material", "price", "made", "seen", "ok", "doc", "raw", "weight", "tag", "note"]


class Env:
    def __init__(self, env: WriteEnv, connection_id: str, admin: sqlalchemy.Engine, prefix: str) -> None:
        self.env, self.connection_id, self.admin, self.prefix = env, connection_id, admin, prefix

    def sql(self, statement: str) -> list[tuple[Any, ...]]:
        with self.admin.begin() as connection:
            result = connection.exec_driver_sql(statement.format(p=self.prefix))
            return [tuple(row) for row in result] if result.returns_rows else []

    def page(self) -> dict[int, dict[str, Any]]:
        """The rows as the viewer shows them (the page's ``old`` values), by id."""
        query = urlencode({"schema": self.prefix, "name": "parts", "limit": 100})
        answer = self.env.send("GET", f"/api/connections/{self.connection_id}/rows?{query}")
        assert answer.status_code == 200, answer.text
        doc = answer.json()
        names = [column["name"] for column in doc["columns"]]
        assert names == COLUMNS and doc["truncated_cells"] == []
        return {row[0]: dict(zip(names, row, strict=True)) for row in doc["rows"]}

    def plan(self, changes: list[dict[str, Any]], table: str = "parts", columns: list[str] | None = None) -> Any:
        request = {"schema": self.prefix, "table": table, "columns": columns or COLUMNS, "changes": changes}
        body = {"connection_id": self.connection_id, "executor": EXECUTOR, "request": request}
        return self.env.send("POST", "/api/write/plans", body)

    def run(self, changes: list[dict[str, Any]]) -> Any:
        preview = self.plan(changes)
        assert preview.status_code == 201, preview.text
        doc = preview.json()
        confirm = {"connection_id": self.connection_id, "plan_hash": doc["plan_hash"], "typed": doc["confirm_text"]}
        assert self.env.send("POST", "/api/write/plans/confirm", confirm).status_code == 200
        execute = {"connection_id": self.connection_id, "plan_hash": doc["plan_hash"]}
        return self.env.send("POST", "/api/write/plans/execute", execute)


